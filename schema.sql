-- ------------------------------------------------------------
-- 1) TABEL PROFIL  (tambah kolom is_admin utk menandai pemilik/admin)
-- ------------------------------------------------------------
create table if not exists public.profil (
    user_id     uuid primary key references auth.users(id) on delete cascade,
    nama        text not null default 'Peserta',
    jml_sesi    int  not null default 8,
    is_admin    boolean not null default false,
    phone       text,
    updated_at  timestamptz default now()
);

-- ------------------------------------------------------------
-- 2) TABEL PERJALANAN SESI (progres per-sesi tiap pengguna)
-- ------------------------------------------------------------
create table if not exists public.perjalanan_sesi (
    id          bigint generated by default as identity primary key,
    user_id     uuid not null references auth.users(id) on delete cascade,
    sesi_num    int  not null,
    sesi_title  text not null,
    pre_score   int,
    post_score  int,
    status      text not null default 'terkunci',
    selesai_at  timestamptz,
    created_at  timestamptz default now(),
    unique (user_id, sesi_num)
);

-- ------------------------------------------------------------
-- 3) TABEL MATERI  (konten sesi: judul, narasi, link embed video)
-- Sesi 1..8 diisi admin; peserta hanya membaca.
-- ------------------------------------------------------------
create table if not exists public.materi (
    id          bigint generated by default as identity primary key,
    sesi_num    int  not null unique,
    judul       text not null,
    deskripsi   text not null,              -- narasi / materi teks
    video_url   text,                        -- URL embed video (YouTube dll)
    mins_watch  int  not null default 15,    -- durasi minimum belajar (menit)
    aktif       boolean not null default true,
    created_at  timestamptz default now(),
    updated_at  timestamptz default now()
);

-- ------------------------------------------------------------
-- 4) TABEL ARTIKEL  (artikel edukasi tambahan)
-- ------------------------------------------------------------
create table if not exists public.artikel (
    id          bigint generated by default as identity primary key,
    judul       text not null,
    kategori    text not null default 'Umum',
    isi         text not null,
    gambar_url  text,
    aktif       boolean not null default true,
    created_at  timestamptz default now()
);

-- ------------------------------------------------------------
-- 5) TABEL TEMPLATE SERTIFIKAT  (background gambar sertifikat)
-- Hanya SATU template aktif yang dipakai peserta saat lulus.
-- ------------------------------------------------------------
create table if not exists public.sertifikat_template (
    id          bigint generated by default as identity primary key,
    nama        text not null,
    gambar_url  text not null,             -- URL gambar background (Storage)
    aktif       boolean not null default false,
    created_at  timestamptz default now()
);

-- ============================================================
-- ROW LEVEL SECURITY
